# The order a license is chosen in from an expression that offers several.
PREFER = ["MIT", "Apache-2.0", "Zlib", "BSD-3-Clause", "BSD-2-Clause", "ISC", "BSL-1.0", "Unicode-3.0",
          "MIT-0", "0BSD", "CC0-1.0", "Unlicense", "BSD-1-Clause"]

LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE|COPYRIGHT)", re.I)


def targets():
    """The systems a release is built for: release/platforms.json's, and the Mac's two."""
    with open(os.path.join(ROOT, "release", "platforms.json")) as f:
        listed = {p["build"]["target"] for p in json.load(f)["platforms"] if p["build"].get("target")}
    return sorted(listed | {"x86_64-apple-darwin", "aarch64-apple-darwin"})


def packages():
    """Every crate linked into the program on a system it ships for (normal dependencies)."""
    found = {}
    for t in targets():
        meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", t],
                                         cwd=ROOT, capture_output=True, text=True, check=True).stdout)
        by_id = {p["id"]: p for p in meta["packages"]}
        nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
        root = meta["resolve"]["root"]
        seen, todo = set(), [root]
        while todo:
            i = todo.pop()
            if i in seen:
                continue
            seen.add(i)
            for d in nodes[i]["deps"]:
                if any(k["kind"] in (None, "normal") for k in d["dep_kinds"]):
                    todo.append(d["pkg"])
        seen.discard(root)
        for i in seen:
            found[i] = by_id[i]
    return sorted(found.values(), key=lambda p: (p["name"], p["version"]))


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read().strip()


def chosen(expr):
    """The license taken from an expression: every part of an AND, the preferred one of an OR."""
    expr = (expr or "").replace("/", " OR ")
    parts = []
    for conj in re.split(r"\bAND\b", expr):
        options = [o.strip(" ()") for o in re.split(r"\bOR\b", conj) if o.strip(" ()")]
        options = [o.split(" WITH ")[0].strip() for o in options]
        pick = next((p for p in PREFER if p in options), options[0] if options else "")
        parts.append(pick)
    return [p for p in parts if p]


def files_for(pkg, picks):
    """The license files a crate ships for the licenses taken (all, where names do not tell)."""
    d = os.path.dirname(pkg["manifest_path"])
    files = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
    if not files:
        return []
    named = {"MIT": "MIT", "Apache-2.0": "APACHE", "Zlib": "ZLIB", "BSL-1.0": "BOOST", "Unicode-3.0": "UNICODE"}
    want = [f for f in files if any(named.get(p, "#") in f.upper() for p in picks)]
    tagged = [f for f in files if any(t in f.upper() for t in named.values())]
    # A crate with LICENSE-MIT and LICENSE-APACHE gives the chosen one; others give all they have.
    keep = want if want else [f for f in files if f not in tagged] or files
    return [os.path.join(d, f) for f in keep]


def standard(pick, pkg, texts_seen):
    authors = ", ".join(a.split("<")[0].strip() for a in pkg.get("authors") or []) or f"the {pkg['name']} authors"
    if pick == "MIT":
        return f"MIT License\n\nCopyright (c) {authors}\n\n{MIT}"
    if pick == "BSL-1.0":
        return BSL
    if pick == "BSD-2-Clause":
        return f"BSD 2-Clause License\n\nCopyright (c) {authors}\n\n{BSD2}"
    if pick == "BSD-3-Clause":
        head, tail = BSD2.split("THIS SOFTWARE")
        return f"BSD 3-Clause License\n\nCopyright (c) {authors}\n\n{head}{BSD3_CLAUSE}\n\nTHIS SOFTWARE{tail}"
    if pick in texts_seen:
        return f"Copyright (c) {authors}\n\n{texts_seen[pick]}"
    sys.exit(f"no text for {pick} ({pkg['name']} {pkg['version']}): add one to scripts/licenses.py")


def main():
    pkgs = packages()
    groups = {}  # text -> list of users
    listing = []
    missing = []
    # Standard texts taken from crates that ship them, for crates that do not.
    texts_seen = {}
    for p in pkgs:
        picks = chosen(p.get("license"))
        for f in files_for(p, picks):
            up = os.path.basename(f).upper()
            if "APACHE" in up and "Apache-2.0" not in texts_seen:
                texts_seen["Apache-2.0"] = read(f)
            if "ZLIB" in up and "Zlib" not in texts_seen:
                texts_seen["Zlib"] = read(f)
    for p in pkgs:
        picks = chosen(p.get("license"))
        name = f"{p['name']} {p['version']}"
        listing.append(f"{name}  ({p.get('license') or 'see its texts'}){'  ' + p['repository'] if p.get('repository') else ''}")
        files = files_for(p, picks)
        # Texts in the sources a crate carries: C and C++ libraries it builds, fonts it embeds.
        inner = []
        d = os.path.dirname(p["manifest_path"])
        for sub in sorted(os.listdir(d)):
            sd = os.path.join(d, sub)
            if not os.path.isdir(sd) or sub in ("src", "tests", "benches", "examples", "target"):
                continue
            for dirpath, dirnames, filenames in os.walk(sd):
                if dirpath[len(sd):].count(os.sep) > 1:
                    dirnames[:] = []
                    continue
                for f in sorted(filenames):
                    if re.match(r"^(LICEN[CS]E|COPYING|PATENTS|NOTICE|OFL|UFL)(\.|$|-)", f, re.I) or f.endswith("-license.txt") or f == "Hack-Regular.txt":
                        inner.append((os.path.relpath(os.path.join(dirpath, f), d), os.path.join(dirpath, f)))
        if files:
            for f in files:
                groups.setdefault(read(f), []).append(name)
        else:
            missing.append(name)
            for pick in picks:
                # A license whose text comes with the sources it covers (a font's OFL) is given there.
                if inner and pick not in ("MIT", "Apache-2.0", "BSL-1.0"):
                    continue
                groups.setdefault(standard(pick, p, texts_seen), []).append(name)
        for rel, path in inner:
            # A library offered under BSD or the GPL (zstd) is taken under the BSD text beside it.
            here = os.listdir(os.path.dirname(path))
            if os.path.basename(path).upper().startswith("COPYING") and "GNU GENERAL PUBLIC LICENSE" in read(path) and any(f.upper().startswith("LICENSE") for f in here):
                continue
            groups.setdefault(read(path), []).append(f"{name}: {rel}")
    # What the repository carries itself.
    for rel, what in [("assets/fonts/LICENSE-phosphor.txt", "Phosphor icons (assets/fonts)"),
                      ("web/LICENSE-xterm.txt", "xterm.js and its fit addon (web)")]:
        groups.setdefault(read(os.path.join(ROOT, rel)), []).append(what)
    out = ["SSH Remote is under the MIT license (see LICENSE). It is built with the open-source software",
           "listed below; their licenses follow, each text once, with what it covers.",
           "This file is made by scripts/licenses.py from Cargo.lock.", "",
           "=" * 100, f"Libraries ({len(listing)})", "=" * 100, ""] + listing + [""]
    for text, users in sorted(groups.items(), key=lambda g: g[1][0].lower()):
        out += ["=" * 100, "Used by: " + ", ".join(users), "=" * 100, "", text, ""]
    body = "\n".join(out).rstrip() + "\n"
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != body:
            sys.exit("THIRD-PARTY-NOTICES.txt is not as Cargo.lock says: run scripts/licenses.py")
        print("THIRD-PARTY-NOTICES.txt is up to date")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"{OUT}: {len(listing)} libraries, {len(groups)} texts, {len(body) // 1024} KB; "
          f"{len(missing)} crates ship no text of their own (standard text with their authors)")


if __name__ == "__main__":
    main()
